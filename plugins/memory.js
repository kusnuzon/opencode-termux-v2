// memory.js — cross-session shared memory for OpenCode.
//
// Two responsibilities:
//   1. the `memory_save` tool → writes facts/decisions to MEMORY.md (always part
//      of the `instructions` in opencode.jsonc, so the next session reads it).
//   2. the compaction hook    → asks the model to move important state into
//      MEMORY.md before the context is compressed, so compaction does not
//      throw away the results of that session.
//
// This file is DUAL-COMPATIBLE (OpenCode V1 and V2 use the same file):
//   - V2 (>= 2.x) calls `setup(ctx)` — the V2 plugin API.
//   - V1 (>= 1.18.29) reads the default export and calls `server()` — the V1 API.
// Both register a tool with the same name, so the tools never clash.
//
// MEMORY.md format: a "# MEMORY" title on the first line, then a "## Log"
// section as the last section. New entries are always appended to the end of the
// file (the Log part). A hard MAX_BYTES cap keeps the file from growing and
// eating context.

import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { dirname, join } from "node:path"

const MEMORY = join(homedir(), ".config", "opencode", "MEMORY.md")
const MAX_BYTES = 24000

// Summary of the most recent sessions (RECENT.md), regenerated by this script on
// every memory_save / before compaction / when opencode starts from ~/.bashrc.
const DIGEST_SCRIPT = join(homedir(), ".config", "opencode", "bin", "session-digest.py")

async function refreshDigest() {
  if (!existsSync(DIGEST_SCRIPT)) return
  try {
    const { spawn } = await import("node:child_process")
    const child = spawn("python3", [DIGEST_SCRIPT], { detached: true, stdio: "ignore" })
    child.on("error", () => {})
    child.unref()
  } catch (error) {
    console.error("[memory] failed to refresh RECENT.md:", error?.message ?? error)
  }
}

const TOOL_DESCRIPTION =
  "Save one fact to permanent cross-session memory (MEMORY.md). Call it after finishing something that must be remembered in a later chat: decisions, user preferences, file locations, troubleshooting results, or configuration changes. Do not use it for transient conversation content."

const ENTRY_DESC = "One fact or decision, concrete and short. Include absolute paths and numbers."
const KIND_DESC = "Memory kind, default: fact"
const TAGS_DESC = "Short labels for later lookup, e.g. setup, vault, termux"
const KINDS = ["fact", "decision", "preference", "gotcha", "config"]

const COMPACT_PROMPT = [
  "## Memory persistence (required before the context is compressed)",
  "",
  "Call the `memory_save` tool for anything that must survive compaction:",
  "- decisions just made and the reasoning behind them",
  "- files/configuration that were changed (absolute paths)",
  "- troubleshooting results that may come up again",
  "- unfinished work and the next steps",
  "",
  "At most 3 entries, only ones that cannot be re-derived from file contents.",
].join("\n")

// --- core (shared by V1 and V2) ---------------------------------------------
function readMemory() {
  if (!existsSync(MEMORY)) return ""
  return readFileSync(MEMORY, "utf8")
}

function writeMemory(text) {
  mkdirSync(dirname(MEMORY), { recursive: true })
  writeFileSync(MEMORY, text.endsWith("\n") ? text : text + "\n")
}

function appendLog(body) {
  let text = readMemory()
  if (!text.trim()) {
    writeMemory("# MEMORY\n\n## Log\n\n" + body)
    return
  }
  if (!text.startsWith("# MEMORY")) text = "# MEMORY\n\n" + text
  if (!text.includes("## Log")) text = text.trimEnd() + "\n\n## Log\n\n"
  text = text.trimEnd() + "\n" + body
  writeMemory(text)
}

// saveEntry — shared by both APIs. Throws an Error on failure.
function saveEntry(args) {
  const entry = String(args?.entry ?? "").trim()
  if (!entry) throw new Error("empty entry")

  const current = readMemory()
  if (current.includes(entry)) return "Already recorded in MEMORY.md, duplicate skipped: " + entry

  if (current && statSync(MEMORY).size + entry.length > MAX_BYTES)
    throw new Error(
      `MEMORY.md is already ${statSync(MEMORY).size} bytes (limit ${MAX_BYTES}). Prune stale entries first so the file stays cheap to load in every session.`,
    )

  const date = new Date().toISOString().slice(0, 10)
  const tags = (args?.tags ?? []).filter(Boolean).map((t) => " #" + t)
  const kind = KINDS.includes(args?.kind) ? args.kind : "fact"
  appendLog(`- (${date}) [${kind}${tags.join("")}] ${entry}`)
  void refreshDigest()

  const lines = readMemory().split("\n").length
  return `Saved to MEMORY.md (${lines} lines, ${statSync(MEMORY).size} bytes): ${entry}`
}

// --- API V2 -----------------------------------------------------------------
const V2_INPUT = {
  type: "object",
  properties: {
    entry: { type: "string", description: ENTRY_DESC },
    kind: { type: "string", enum: KINDS, description: KIND_DESC },
    tags: { type: "array", items: { type: "string" }, description: TAGS_DESC },
  },
  required: ["entry"],
  additionalProperties: false,
}

// --- API V1 -----------------------------------------------------------------
// the `tool` helper only exists in the V1 package ("@opencode-ai/plugin"), so it
// is imported dynamically inside server(); V2 never calls this part.
async function v1Hooks() {
  const mod = await import("@opencode-ai/plugin").catch(() => null)
  const tool = mod?.tool
  if (!tool) return {}
  return {
    tool: {
      memory_save: tool({
        description: TOOL_DESCRIPTION,
        args: {
          entry: tool.schema.string().describe(ENTRY_DESC),
          kind: tool.schema.enum(KINDS).optional().describe(KIND_DESC),
          tags: tool.schema.array(tool.schema.string()).optional().describe(TAGS_DESC),
        },
        async execute(args) {
          return saveEntry(args)
        },
      }),
    },
    "experimental.session.compacting": async (_input, output) => {
      output.context.push(COMPACT_PROMPT)
      void refreshDigest()
    },
  }
}

// --- default export (used by V1 & V2) ---------------------------------------
export default {
  id: "memory",

  // V2: called by the V2 plugin host.
  async setup(ctx) {
    if (typeof ctx?.tool?.transform !== "function") return
    await ctx.tool.transform((editor) => {
      editor.add({
        name: "memory_save",
        description: TOOL_DESCRIPTION,
        input: V2_INPUT,
        async execute(input) {
          // V2: a tool must return { content } (not { output }) when it does
          // not declare an output schema.
          return { content: saveEntry(input) }
        },
      })
    })

    try {
      await ctx.session.hook("compaction", async (event) => {
        if (Array.isArray(event?.system)) event.system.push({ type: "text", text: COMPACT_PROMPT })
        void refreshDigest()
      })
    } catch (error) {
      console.error("[memory] compaction hook failed:", error?.message ?? error)
    }
  },

  // V1: called by the V1 plugin host.
  async server() {
    return await v1Hooks()
  },
}
